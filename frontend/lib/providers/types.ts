/**
 * Create a standardized provider response with metadata.
 */
export function createProviderResponse(
  source: string,
  raw: Record<string, unknown>,
  normalized?: Record<string, unknown>
): ProviderResponse {
  return {
    _source: source,
    _retrieved_at: new Date().toISOString(),
    raw,
    normalized,
  };
}

/**
 * Create a standardized contact response.
 */
export function createContactResponse(
  source: string,
  contact: Omit<ContactResponse, '_source' | '_retrieved_at'>
): ContactResponse {
  return {
    _source: source,
    _retrieved_at: new Date().toISOString(),
    ...contact,
  };
}

/**
 * Format revenue number as human-readable string.
 */
export function formatRevenue(revenue: number | string | null | undefined): string {
  if (revenue === null || revenue === undefined) {
    return 'Unknown';
  }

  let numRevenue: number;
  if (typeof revenue === 'string') {
    numRevenue = parseFloat(revenue);
    if (isNaN(numRevenue)) {
      return revenue;
    }
  } else {
    numRevenue = revenue;
  }

  if (numRevenue >= 1_000_000_000) {
    return `$${(numRevenue / 1_000_000_000).toFixed(1)}B`;
  }
  if (numRevenue >= 1_000_000) {
    return `$${Math.round(numRevenue / 1_000_000)}M`;
  }
  if (numRevenue >= 1_000) {
    return `$${Math.round(numRevenue / 1_000)}K`;
  }
  return `$${Math.round(numRevenue)}`;
}
